// Generates keys.js for the storefront and admin console.
// Usage: LH_ADMIN_PASSWORD='long passphrase' node tools/gen-keys.mjs <adminDir> <storefrontDir>
// Re-run (and redeploy BOTH sites) to rotate the admin password. Old orders on the relay become unreadable.
import { webcrypto as crypto } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const password = process.env.LH_ADMIN_PASSWORD;
const outDirs = process.argv.slice(2);
if (!password || password.length < 8 || !outDirs.length) {
  console.error('Set LH_ADMIN_PASSWORD (min 8 chars) and pass at least one output directory.');
  process.exit(1);
}

const b64 = (buf) => Buffer.from(buf).toString('base64');
const enc = new TextEncoder();
const ITER = 310000;

const encPair = await crypto.subtle.generateKey(
  { name: 'RSA-OAEP', modulusLength: 2048, publicExponent: new Uint8Array([1, 0, 1]), hash: 'SHA-256' },
  true,
  ['encrypt', 'decrypt']
);
const sigPair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);

const priv = {
  enc: await crypto.subtle.exportKey('jwk', encPair.privateKey),
  sig: await crypto.subtle.exportKey('jwk', sigPair.privateKey)
};
const pub = {
  enc: await crypto.subtle.exportKey('jwk', encPair.publicKey),
  sig: await crypto.subtle.exportKey('jwk', sigPair.publicKey)
};

const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const material = await crypto.subtle.importKey('raw', enc.encode(password), 'PBKDF2', false, ['deriveKey']);
const wrapKey = await crypto.subtle.deriveKey(
  { name: 'PBKDF2', salt, iterations: ITER, hash: 'SHA-256' },
  material,
  { name: 'AES-GCM', length: 256 },
  false,
  ['encrypt']
);
const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, wrapKey, enc.encode(JSON.stringify(priv)));

const wrap = { salt: b64(salt), iter: ITER, iv: b64(iv), ct: b64(ct) };
const header = '/* Generated by tools/gen-keys.mjs. */\n';
// The first directory is the admin console (public keys + wrapped private keys); the rest get public keys only.
outDirs.forEach((dir, index) => {
  const keys = index === 0 ? { enc: pub.enc, sig: pub.sig, wrap } : { enc: pub.enc, sig: pub.sig };
  writeFileSync(join(dir, 'keys.js'), `${header}window.LH_KEYS = ${JSON.stringify(keys)};\n`);
  console.log('wrote', join(dir, 'keys.js'), index === 0 ? '(admin)' : '(public only)');
});
